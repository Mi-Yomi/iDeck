func runEnvironmentStartupChecks() {
    precondition(LinuxEnvironmentStartup.completes(command:"INSTALL",status:"IDECK_STEAM_INSTALLED"))
    precondition(!LinuxEnvironmentStartup.completes(command:"BIG_PICTURE",status:"IDECK_STEAM_INSTALLED"))
    precondition(!LinuxEnvironmentStartup.completes(command:"DESKTOP",status:"IDECK_STEAM_CLIENT_RETURNED"))
    precondition(LinuxEnvironmentStartup.completes(command:"DESKTOP",status:"IDECK_STEAM_DESKTOP_READY"))
    precondition(!LinuxEnvironmentStartup.completes(command:nil,status:"IDECK_STEAM_INSTALLED"))
    precondition(LinuxEnvironmentStartup.acknowledgesLaunch(command:"BIG_PICTURE",status:"IDECK_STEAM_LAUNCH_REQUESTED"))
    precondition(!LinuxEnvironmentStartup.acknowledgesLaunch(command:"INSTALL",status:"IDECK_STEAM_LAUNCH_REQUESTED"))
    precondition(!LinuxEnvironmentStartup.acknowledgesLaunch(command:"DESKTOP",status:"IDECK_STEAM_LAUNCH_REQUESTED"))
    var intent = LinuxEnvironmentLaunchIntent()
    precondition(intent.begin() && !intent.begin())
    precondition(intent.advance(owner:false,foreground:false,busy:false,network:true,jit:true) == .wait)
    precondition(intent.advance(owner:false,foreground:true,busy:true,network:true,jit:true) == .wait)
    // First launch with JIT off shows an actionable prompt, not a pending spinner.
    precondition(intent.advance(owner:false,foreground:true,busy:false,network:false,jit:false) == .jit)
    precondition(!intent.pending && intent.jitPrompt)
    precondition(intent.begin())
    precondition(intent.advance(owner:false,foreground:true,busy:false,network:true,jit:false) == .jit)
    intent.checkedJIT(false); precondition(intent.jitPrompt && !intent.pending)
    // Returning from another app is not evidence of JIT; only the actual check is.
    intent.checkedJIT(true); precondition(!intent.jitPrompt && !intent.pending)
    precondition(intent.advance(owner:false,foreground:true,busy:false,network:true,jit:true) == .wait)
    precondition(intent.begin()) // Explicit continue; no auto-start on return.
    precondition(intent.advance(owner:false,foreground:true,busy:false,network:false,jit:true) == .consent)
    precondition(intent.advance(owner:false,foreground:true,busy:false,network:true,jit:true) == .start)
    precondition(intent.advance(owner:false,foreground:true,busy:false,network:true,jit:true) == .wait)
    precondition(intent.begin())
    precondition(intent.advance(owner:true,foreground:true,busy:false,network:false,jit:false) == .resume)
    precondition(!intent.pending && !intent.jitPrompt)
    precondition(intent.begin()); intent.cancel()
    precondition(intent.advance(owner:false,foreground:true,busy:false,network:true,jit:true) == .wait)

    var environment = LinuxEnvironmentStartup()
    precondition(environment.observe("IDECK_STEAM_INSTALLED") == nil && !environment.installed)
    environment.begin(); environment.begin()
    precondition(environment.stage == .waitingDesktop && !environment.installed)
    precondition(environment.desktopReady() == .install)
    for _ in 0..<20 { precondition(environment.desktopReady() == nil && !environment.installed) }
    environment.timedOut()
    precondition(environment.stage == .waitingConfirmation && environment.pending == .install)
    precondition(environment.retry() == nil, "timeout is not proof that the guest command ended")
    precondition(environment.observe("IDECK_STEAM_INSTALLED") == .openSteam)
    precondition(environment.installed && environment.pending == .openSteam)
    precondition(environment.observe("IDECK_STEAM_INSTALLED") == nil)
    precondition(environment.observe("IDECK_STEAM_LAUNCH_REQUESTED") == nil)
    precondition(environment.stage == .openingSteam)
    environment.timedOut(); precondition(environment.retry() == nil)
    precondition(environment.observe("IDECK_STEAM_CLIENT_RETURNED") == nil)
    precondition(environment.stage == .desktop && environment.pending == nil)
    for _ in 0..<20 { precondition(environment.desktopReady() == nil) }

    var failure = LinuxEnvironmentStartup(); failure.begin()
    precondition(failure.desktopReady() == .install)
    precondition(failure.observe("IDECK_STEAM_BLOCKER:package_failed") == nil)
    precondition(failure.stage == .blocked && !failure.installed)
    precondition(failure.desktopReady() == nil)
    precondition(failure.retry() == .install && failure.retry() == nil)
    failure.stop()
    precondition(failure.observe("IDECK_STEAM_INSTALLED") == nil && !failure.installed)
    precondition(failure.desktopReady() == nil && failure.retry() == nil)
    failure.begin(); precondition(failure.stage == .stopped)
    var beforeReady = LinuxEnvironmentStartup(); beforeReady.begin(); beforeReady.stop()
    precondition(beforeReady.desktopReady() == nil)
    // Home/settings/resume changes only navigation; the same pending install remains.
    var navigation = LinuxLauncherNavigation(); precondition(navigation.open(.steam)); navigation.reserve(.steam)
    var live = LinuxEnvironmentStartup(); live.begin(); precondition(live.desktopReady() == .install)
    for _ in 0..<20 {
        navigation.home(); precondition(navigation.open(.settings)); navigation.resume()
        precondition(navigation.destination == .steam && !navigation.open(.desktop))
        precondition(live.pending == .install && live.desktopReady() == nil)
    }
    let report = LinuxProbeReport.render(report:["mode":"steam-experimental","environment_stage":"waitingConfirmation"])
    precondition(report.contains("| Environment setup stage | waitingConfirmation |"))
    let unknown = LinuxProbeReport.render(report:["mode":"steam-experimental","environment_stage":"PRIVATE_STAGE_CANARY"])
    precondition(unknown.contains("| Environment setup stage | UNKNOWN |") && !unknown.contains("PRIVATE_STAGE_CANARY"))
    var selection = LinuxLauncherNavigation(); precondition(selection.open(.desktop)); selection.home()
    selection.selectPrimary(); precondition(selection.selected == .steam && selection.destination == .choose)
    precondition(selection.open(.desktop)); selection.reserve(.desktop)
    selection.selectPrimary(); precondition(selection.selected == .desktop && selection.owner == .desktop)
    print("LINUX_UNIFIED_ENVIRONMENT_PASS (owner resume, JIT/consent/foreground, repeat/cancel, one install/launch, late receipt, timeout no retry, Stop, Home)")
}
