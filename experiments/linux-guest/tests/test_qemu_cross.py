"""Cross-file policy and patch guards; fixtures never compile or run iOS code.

The small shell fixture is synthetic and contains the exact pinned configure
hunk context. Full upstream configure application is a separate host control.
"""
import ast
import configparser
import contextlib
import io
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "ci"))
import build_linux_probe_ipa as build

PATCH = ROOT / "experiments/linux-guest/ipa/0002-qemu-ios-needs-exe-wrapper.patch"
QEMU_DIRECTORY = "third_party/build/qemu-10.0.12-utm"
# Exact six unchanged hunk lines from v10.0.12-utm configure, wrapped in a
# deliberately small host-shell fixture rather than represented as QEMU itself.
FIXTURE = '''#!/bin/sh
set -eu
cross="$1"
cross_compile="$2"
skip_meson=no
device_archs=""
if test "$skip_meson" = no; then

  echo "# Automatically generated by configure - do not modify" > $cross
  echo "[properties]" >> $cross

  # unroll any custom device configs
  for a in $device_archs; do
    : "$a"
  done
  echo "[host_machine]" >> $cross
  echo "system = 'darwin'" >> $cross
  echo "cpu_family = 'aarch64'" >> $cross
fi
'''
ADDITION = '''  # This iOS recipe's Darwin/arm64 device binaries cannot execute on macOS.
  if test "$cross_compile" = "yes"; then
    echo "needs_exe_wrapper = true" >> $cross
  fi
'''


class QemuCrossTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        # TMPDIR can live inside the transport checkout. Without an explicit
        # root, git discovers its parent repo and interprets --directory using
        # that cwd prefix, silently skipping the intended fixture paths.
        initialized = subprocess.run(["git", "init", "--quiet", str(self.root)],
                                     stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
        self.assertEqual(initialized.returncode, 0, initialized.stderr)
        self.configure = self.root / QEMU_DIRECTORY / "configure"
        self.configure.parent.mkdir(parents=True)
        self.configure.write_text(FIXTURE)

    def apply(self, check=False):
        command = ["git", "apply"]
        if check:
            command.append("--check")
        command.extend(["--directory=" + QEMU_DIRECTORY, str(PATCH)])
        return subprocess.run(command, cwd=self.root, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)

    def apply_successfully(self):
        before = self.configure.read_bytes()
        check = self.apply(check=True)
        self.assertEqual(check.returncode, 0, check.stderr)
        self.assertEqual(self.configure.read_bytes(), before, "--check must not mutate sources")
        applied = self.apply()
        self.assertEqual(applied.returncode, 0, applied.stderr)

    def generated_config(self, cross_compile):
        output = self.root / ("meson-" + cross_compile + ".cross")
        result = subprocess.run(["sh", str(self.configure), str(output), cross_compile],
                                cwd=self.root, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        parser = configparser.ConfigParser(interpolation=None)
        parser.read(output)
        return parser, output.read_text()

    def test_checked_patch_changes_only_conditional_cross_wrapper_property(self):
        self.apply_successfully()
        expected = FIXTURE.replace('  echo "[properties]" >> $cross\n',
                                   '  echo "[properties]" >> $cross\n' + ADDITION)
        self.assertEqual(self.configure.read_text(), expected)
        self.assertEqual(self.configure.read_text().count("needs_exe_wrapper = true"), 1)

    def test_ios_cross_branch_requires_wrapper_without_inventing_one(self):
        self.apply_successfully()
        parser, raw = self.generated_config("yes")
        self.assertTrue(parser.getboolean("properties", "needs_exe_wrapper"))
        self.assertEqual(parser["host_machine"]["system"], "'darwin'")
        self.assertEqual(parser["host_machine"]["cpu_family"], "'aarch64'")
        self.assertNotIn("[binaries]", raw)
        self.assertNotIn("exe_wrapper =", raw.replace("needs_exe_wrapper =", "property ="))

    def test_native_branch_keeps_original_no_wrapper_behavior(self):
        self.apply_successfully()
        for value in ("no", ""):
            with self.subTest(cross_compile=value):
                parser, raw = self.generated_config(value)
                self.assertFalse(parser.has_option("properties", "needs_exe_wrapper"))
                self.assertEqual(parser["host_machine"]["system"], "'darwin'")
                self.assertNotIn("needs_exe_wrapper", raw)

    def test_changed_pinned_context_is_rejected_without_mutation(self):
        changed = FIXTURE.replace('echo "[properties]"', 'echo "[unreviewed_properties]"')
        self.configure.write_text(changed)
        result = self.apply(check=True)
        self.assertNotEqual(result.returncode, 0)
        self.assertEqual(self.configure.read_text(), changed)
        self.assertNotIn("needs_exe_wrapper", self.configure.read_text())

    def test_second_application_fails_instead_of_silently_accepting_stale_state(self):
        self.apply_successfully()
        original = self.configure.read_bytes()
        result = self.apply(check=True)
        self.assertNotEqual(result.returncode, 0)
        self.assertEqual(self.configure.read_bytes(), original)

    def test_directory_guard_preserves_other_configure_files(self):
        outside = self.root / "configure"
        outside.write_text("unrelated source must remain unchanged\n")
        self.configure.unlink()
        result = self.apply(check=True)
        self.assertNotEqual(result.returncode, 0)
        self.assertEqual(outside.read_text(), "unrelated source must remain unchanged\n")

    def test_patch_error_propagates_through_worker_with_retained_log(self):
        self.configure.write_text("unreviewed source\n")
        with tempfile.TemporaryDirectory() as output:
            worker = build.Worker(Path(output))
            with contextlib.redirect_stdout(io.StringIO()), self.assertRaises(RuntimeError):
                worker.run("qemu-cross-patch-check", ["git", "apply", "--check",
                           "--directory=" + QEMU_DIRECTORY, PATCH], self.root)
            self.assertNotEqual(worker.steps[-1]["exit_code"], 0)
            self.assertTrue((Path(output) / "qemu-cross-patch-check.log").read_text())
            self.assertEqual(self.configure.read_text(), "unreviewed source\n")

    def test_check_and_apply_are_both_required_before_real_qemu_build(self):
        tree = ast.parse(Path(build.__file__).read_text())
        main = next(node for node in tree.body if isinstance(node, ast.FunctionDef) and node.name == "main")
        calls = {node.args[0].value: node for node in ast.walk(main)
                 if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)
                 and node.func.attr == "run" and node.args and isinstance(node.args[0], ast.Constant)}
        ordered = ("native-gpu", "qemu-cross-patch-check", "qemu-cross-patch-apply", "native-qemu",
                   "native-integrate-husk", "native-qemu-integrated")
        self.assertEqual([calls[name].lineno for name in ordered], sorted(calls[name].lineno for name in ordered))
        checked_args = calls["qemu-cross-patch-check"].args[1]
        applied_args = calls["qemu-cross-patch-apply"].args[1]
        self.assertIn("--check", [node.value for node in checked_args.elts if isinstance(node, ast.Constant)])
        self.assertNotIn("--check", [node.value for node in applied_args.elts if isinstance(node, ast.Constant)])
        directories = [node for node in ast.walk(main) if isinstance(node, ast.Assign)
                       and any(isinstance(name, ast.Name) and name.id == "qemu_directory" for name in node.targets)]
        self.assertEqual(len(directories), 1)
        self.assertEqual(directories[0].value.value, "--directory=" + QEMU_DIRECTORY)
        self.assertEqual(calls["native-qemu"].args[1].elts[-1].value, "qemu")
        self.assertEqual(calls["native-qemu-integrated"].args[1].elts[-1].value, "qemurebuild")


if __name__ == "__main__":
    unittest.main()
