#!/usr/bin/env python3
"""Separate exact GUI payload transport and Xcode resources; stdlib, no system installs.

The committed lock is the trust root. A private HTTPS URL is only a transport;
its value (possibly a signed credential) is never included in receipts/logs.
"""
import argparse
import errno
import gzip
import hashlib
import http.client
import json
import os
from pathlib import Path
import re
import shutil
import socket
import ssl
import tarfile
import tempfile
import time
import urllib.request
import urllib.parse
import urllib.error

NAMES = {"vmlinuz-virt", "initramfs-desktop.gz", "gui-rootfs-v1.raw",
         "desktop-profile.json", "LICENSES-desktop.txt"}
ROOTFS="gui-rootfs-v1.raw"
ROOTFS_SIZE=1_342_177_280
KERNEL_SHA256="47970e0ee0478fe5c60824a89f162d5a353fa29466e5d3bddb0f9c506f1ed756"



def prepare(seed, modules, output, lock_path):
    """Rebuild an already approved exact payload; never invent acceptance."""
    lock=load_lock(lock_path)
    experiment=Path(__file__).resolve().parents[1]
    for name,expected in lock["inputs"]["seed"].items(): checked(seed/name,expected)
    checked(modules/"manifest.json",lock["inputs"]["modules"])
    for name,expected in lock["inputs"]["guest"].items(): checked(experiment/"guest/gui"/name,expected)
    output.mkdir(parents=True,exist_ok=False)
    from gui_bootstrap import prepare as bootstrap
    receipt=bootstrap(output/"bootstrap",modules)
    bundle=output/"bundle";bundle.mkdir()
    for name in ("vmlinuz-virt","initramfs-desktop.gz"):shutil.copyfile(output/"bootstrap"/name,bundle/name)
    shutil.copyfile(seed/"gui-rootfs-v1.raw",bundle/"gui-rootfs-v1.raw")
    # Profile/notices are small locked text inputs generated by seal_gui_payload.
    for name in ("desktop-profile.json","LICENSES-desktop.txt"):shutil.copyfile(seed/name,bundle/name)
    verify(bundle,lock)
    archive=output/lock["payload"]["filename"]
    transport={name:bundle/name for name in NAMES-{"gui-rootfs-v1.raw"}}
    transport["gui-rootfs-v1.raw.gz"]=seed/"gui-rootfs-v1.raw.gz"
    with tarfile.open(archive,"w",format=tarfile.USTAR_FORMAT) as tar:
        for name,path in sorted(transport.items()):
            checked(path,lock["transport_files"][name])
            info=tarfile.TarInfo(name);info.size=path.stat().st_size;info.mode=0o644
            with path.open("rb") as stream:tar.addfile(info,stream)
    checked(archive,{k:lock["payload"][k] for k in ("size","sha256")})
    return receipt


def metadata(path):
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        while chunk := stream.read(1024 * 1024):
            digest.update(chunk)
    return {"size": path.stat().st_size, "sha256": digest.hexdigest()}


def real_directory(path):
    if path.is_symlink() or any(p.is_symlink() for p in path.parents) or not path.is_dir():
        raise ValueError("unsafe GUI directory")


def safe_destination(path):
    if path.is_symlink() or any(p.is_symlink() for p in path.parents):
        raise ValueError("unsafe GUI destination ancestors")


def checked(path, expected):
    if (path.is_symlink() or not path.is_file() or path.stat().st_size!=expected.get('size')
            or metadata(path) != expected):
        raise ValueError("GUI integrity mismatch: " + path.name)


def load_lock(path):
    if path.is_symlink() or not path.is_file() or path.stat().st_size>128*1024:raise ValueError("invalid GUI payload lock")
    lock=json.loads(path.read_text(encoding="utf-8"))
    validate_lock(lock)
    return lock


def validate_lock(lock):
    if (type(lock.get("schema")) is not int or lock.get("schema")!=1 or lock.get("kind")!="ideck-debian-gui" or lock.get("status")!="ready"
            or set(lock.get("files",{}))!=NAMES
            or set(lock.get("transport_files",{}))!=(NAMES-{ROOTFS})|{ROOTFS+".gz"}):
        raise ValueError("GUI payload is unavailable or not approved by the matching-kernel gate")
    for group in ("files","transport_files"):
        for name,meta in lock[group].items():
            if (set(meta)!={"size","sha256"} or type(meta["size"]) is not int or meta["size"]<=0
                    or not isinstance(meta["sha256"],str) or not re.fullmatch(r"[0-9a-f]{64}",meta["sha256"])):
                raise ValueError("invalid GUI payload metadata")
    if lock["files"][ROOTFS]["size"]!=ROOTFS_SIZE or lock["files"]["vmlinuz-virt"]["sha256"]!=KERNEL_SHA256:
        raise ValueError("GUI payload identity mismatch")
    limits={"vmlinuz-virt":32*1024**2,"initramfs-desktop.gz":128*1024**2,
            "desktop-profile.json":65536,"LICENSES-desktop.txt":256*1024}
    if any(lock["files"][name]["size"]>limit for name,limit in limits.items()):raise ValueError("oversized GUI asset")
    if any(lock["files"][name]!=lock["transport_files"][name] for name in NAMES-{ROOTFS}):raise ValueError("inconsistent GUI transport")
    payload=lock.get("payload",{})
    if (set(payload)!={"filename","size","sha256"} or payload["filename"]!="ideck-debian-gui-v1.tar"
            or type(payload["size"]) is not int or not 0<payload["size"]<=2*1024**3
            or not isinstance(payload["sha256"],str) or not re.fullmatch(r"[0-9a-f]{64}",payload["sha256"])):
        raise ValueError("invalid GUI archive contract")
    gate=lock.get("acceptance",{})
    if (gate.get("kind")!="production-alpine-two-boots" or gate.get("matching_kernel_gui") is not True
            or gate.get("two_boots_clean") is not True or gate.get("kernel_sha256")!=KERNEL_SHA256
            or gate.get("rootfs_sha256")!=lock["files"][ROOTFS]["sha256"]
            or gate.get("initramfs_sha256")!=lock["files"]["initramfs-desktop.gz"]["sha256"]
            or not re.fullmatch(r"[0-9a-f]{64}",str(gate.get("report_sha256","")))):
        raise ValueError("GUI matching-kernel acceptance is absent or for different bytes")
    return lock


class HTTPSOnlyRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        if urllib.parse.urlsplit(newurl).scheme != "https":
            raise ValueError("payload redirect is not HTTPS")
        redirected = super().redirect_request(req, fp, code, msg, headers, newurl)
        if redirected is not None:
            # GitHub hands back a signed asset URL; never forward the API token.
            redirected.remove_header("Authorization")
        return redirected


def verify(source, lock):
    validate_lock(lock)
    real_directory(source)
    if {p.name for p in source.iterdir()} != NAMES:
        raise ValueError("GUI bundle must contain exactly the locked files")
    for name, expected in lock["files"].items():
        checked(source / name, expected)
    return lock["files"]


def stage(source, destination, lock_path):
    lock = load_lock(lock_path)
    verify(source, lock)
    if destination.resolve() == source.resolve() or source.resolve() in destination.resolve().parents:
        raise ValueError("GUI destination overlaps source")
    safe_destination(destination)
    destination.mkdir(parents=True, exist_ok=True)
    real_directory(destination)
    if any(p.name not in NAMES or p.is_symlink() or not p.is_file() for p in destination.iterdir()):
        raise ValueError("unexpected GUI destination contents")
    for name in sorted(NAMES):
        fd, temporary = tempfile.mkstemp(prefix=".gui-stage-", dir=destination)
        try:
            with os.fdopen(fd, "wb") as target, (source / name).open("rb") as origin:
                shutil.copyfileobj(origin, target, 1024 * 1024)
                target.flush(); os.fsync(target.fileno())
            checked(Path(temporary), lock["files"][name])
            os.replace(temporary, destination / name)
        finally:
            Path(temporary).unlink(missing_ok=True)
    return verify(destination, lock)


def restore(archive, destination, lock_path):
    lock = load_lock(lock_path)
    checked(archive, {k: lock["payload"][k] for k in ("size", "sha256")})
    safe_destination(destination)
    if destination.exists() or destination.is_symlink():
        raise ValueError("GUI restore destination must be new")
    # Validate the ENTIRE flat archive before writing. No extraction of links,
    # devices, duplicates, traversal or unbounded decompressed content.
    expected = (NAMES - {"gui-rootfs-v1.raw"}) | {"gui-rootfs-v1.raw.gz"}
    with tarfile.open(archive, "r:") as tar:
        members = tar.getmembers()
        if (len(members) != len(expected) or {m.name for m in members} != expected
                or any(not m.isfile() or m.size != lock["transport_files"][m.name]["size"] for m in members)):
            raise ValueError("unexpected GUI payload members")
        destination.mkdir(parents=True)
        real_directory(destination)
        if shutil.disk_usage(destination).free < (sum(x["size"] for x in lock["files"].values())
                + lock["transport_files"]["gui-rootfs-v1.raw.gz"]["size"] + 512 * 1024**2):
            raise ValueError("insufficient space for GUI bundle")
        for member in members:
            path = destination / member.name
            with path.open("xb") as target, tar.extractfile(member) as origin:
                shutil.copyfileobj(origin, target, 1024 * 1024)
            checked(path, lock["transport_files"][member.name])
        compressed = destination / "gui-rootfs-v1.raw.gz"
        expected_size = lock["files"]["gui-rootfs-v1.raw"]["size"]
        count = 0
        with gzip.open(compressed, "rb") as origin, (destination / "gui-rootfs-v1.raw").open("xb") as target:
            while chunk := origin.read(1024 * 1024):
                count += len(chunk)
                if count > expected_size:
                    raise ValueError("GUI seed exceeds locked size")
                target.write(chunk)
        checked(destination / "gui-rootfs-v1.raw", lock["files"]["gui-rootfs-v1.raw"])
        compressed.unlink()
    return verify(destination, lock)


class FetchError(RuntimeError):
    """Only a fixed code and an allowlisted diagnostic may cross the CI boundary."""
    def __init__(self, diagnostic):
        self.diagnostic = diagnostic
        super().__init__(diagnostic["code"])


def _numeric(value):
    return value if type(value) is int else None


def _fetch_error(error):
    # URLError wraps TLS/socket failures. Never stringify its reason (which
    # may instead be a URL), headers, body, args, notes or exception chain.
    status = _numeric(error.code) if isinstance(error, urllib.error.HTTPError) else None
    for _ in range(8):
        if type(error) is not urllib.error.URLError or not isinstance(error.reason, Exception):
            break
        error = error.reason
    classes = (Exception, RuntimeError, ValueError, TypeError, KeyError, OSError,
               FileNotFoundError, FileExistsError, PermissionError, IsADirectoryError,
               NotADirectoryError, TimeoutError, ConnectionError, ConnectionResetError,
               ConnectionAbortedError, ConnectionRefusedError, BrokenPipeError,
               socket.gaierror, socket.herror, UnicodeEncodeError, json.JSONDecodeError,
               urllib.error.HTTPError, urllib.error.URLError, ssl.SSLError,
               ssl.SSLCertVerificationError, ssl.SSLEOFError, ssl.SSLZeroReturnError,
               http.client.IncompleteRead, http.client.RemoteDisconnected,
               http.client.BadStatusLine, http.client.LineTooLong, http.client.InvalidURL)
    # Even a custom exception class name could be attacker-controlled text.
    name = type(error).__name__ if type(error) in classes else "Exception"
    return {"exception_class": name, "http_status": status,
            "errno": _numeric(getattr(error, "errno", None))}


def fetch(destination, lock_path, *, diagnostic=None):
    """Download once, fail closed and emit only bounded, secret-free evidence.

    sha256 covers bytes received (including IncompleteRead.partial), not an
    HTTP error body. 'complete' means EOF at the locked size, not a hash match.
    """
    started = time.monotonic()
    digest = hashlib.sha256()
    count = 0
    complete = False
    expected_size = None
    http_status = None
    fd = temporary = target = response = None
    failure = None
    published = False
    code = "GUI_FETCH_CONFIG_LOCK"
    try:
        lock = load_lock(lock_path)
        expected_size = _numeric(lock["payload"]["size"])
        expected_hash = lock["payload"]["sha256"]
        if (type(expected_size) is not int or expected_size <= 0
                or not isinstance(expected_hash, str) or not re.fullmatch(r"[0-9a-f]{64}", expected_hash)):
            expected_size = None
            raise ValueError()
        code = "GUI_FETCH_CONFIG_URL"
        url = os.environ.get("IDECK_GUI_PAYLOAD_URL", "")
        parsed = urllib.parse.urlsplit(url)
        if parsed.scheme != "https" or not parsed.hostname or parsed.username or parsed.password:
            raise ValueError()
        token = os.environ.get("IDECK_GUI_PAYLOAD_TOKEN", "")
        code = "GUI_FETCH_CONFIG_TOKEN_SCOPE"
        github_asset = (parsed.hostname == "api.github.com" and parsed.port in (None, 443)
                        and parsed.username is None and parsed.password is None
                        and not parsed.query and not parsed.fragment
                        and re.fullmatch(r"/repos/Mi-Yomi/iDeck/releases/assets/[0-9]+", parsed.path))
        # Reuse the already imported CI credential only for the SAME approved
        # asset API. Never even read this fallback for another transport URL.
        if not token and github_asset:
            token = os.environ.get("IDECK_DEBIAN_PAYLOAD_TOKEN", "")
        if token and not github_asset:
            raise ValueError()
        code = "GUI_FETCH_CONFIG_DESTINATION"
        if destination.exists() or destination.is_symlink():
            raise ValueError()
        safe_destination(destination)
        code = "GUI_FETCH_WRITE_FAILED"
        destination.parent.mkdir(parents=True, exist_ok=True)
        real_directory(destination.parent)
        fd, temporary = tempfile.mkstemp(prefix=".gui-download-", dir=destination.parent)
        target = os.fdopen(fd, "wb")
        fd = None  # target now owns the descriptor, including on failures.
        code = "GUI_FETCH_OPEN_FAILED"
        request = urllib.request.Request(url, headers={"Accept": "application/octet-stream"})
        if token:
            request.add_unredirected_header("Authorization", "Bearer " + token)
        deadline = time.monotonic() + 300
        response = urllib.request.build_opener(HTTPSOnlyRedirect).open(request, timeout=60)
        http_status = _numeric(getattr(response, "status", None))
        while True:
            code = "GUI_FETCH_READ_FAILED"
            if time.monotonic() > deadline:
                raise TimeoutError()
            try:
                chunk = response.read(1024 * 1024)
            except http.client.IncompleteRead as error:
                count += len(error.partial)
                digest.update(error.partial)
                raise
            count += len(chunk)
            digest.update(chunk)
            if not chunk:
                complete = count == expected_size
            if time.monotonic() > deadline:
                raise TimeoutError()
            code = "GUI_FETCH_VERIFY_SIZE"
            if count > expected_size:
                raise ValueError()
            if not chunk:
                break
            code = "GUI_FETCH_WRITE_FAILED"
            if target.write(chunk) != len(chunk):
                raise OSError(errno.EIO, "")
        code = "GUI_FETCH_READ_FAILED"
        response.close()
        response = None
        code = "GUI_FETCH_WRITE_FAILED"
        target.close()  # Includes buffered writes/flush; do not publish on error.
        target = None
        code = "GUI_FETCH_VERIFY_SIZE"
        if count != expected_size:
            raise ValueError()
        code = "GUI_FETCH_VERIFY_HASH"
        if digest.hexdigest() != expected_hash:
            raise ValueError()
        code = "GUI_FETCH_VERIFY_FILE"
        # Keep the independent check of the stored file, not just the stream.
        checked(Path(temporary), {k: lock["payload"][k] for k in ("size", "sha256")})
        code = "GUI_FETCH_PUBLISH_FAILED"
        os.link(temporary, destination)
        published = True
    except Exception as error:
        failure = {"code": code, **_fetch_error(error)}
        if response is None and isinstance(error, urllib.error.HTTPError):
            response = error  # Close the rejected response without reading its body.
    finally:
        # Cleanup failures must not mask the original stage or leak paths/text.
        cleanup = []
        if response is not None: cleanup.append(response.close)
        if target is not None: cleanup.append(target.close)
        if fd is not None: cleanup.append(lambda: os.close(fd))
        if temporary is not None: cleanup.append(lambda: Path(temporary).unlink(missing_ok=True))
        for close in cleanup:
            try:
                close()
            except Exception as error:
                detail = {"code": "GUI_FETCH_CLEANUP_FAILED", **_fetch_error(error)}
                if failure is None: failure = detail
                elif "cleanup_failure" not in failure: failure["cleanup_failure"] = detail
        details = {"code": "GUI_FETCH_OK" if published else "GUI_FETCH_INTERRUPTED", "exception_class": None,
                   "http_status": http_status, "errno": None}
        if failure:
            details.update(failure)
            if details["http_status"] is None: details["http_status"] = http_status
        details.update(received_bytes=count, expected_size=expected_size,
                       sha256=digest.hexdigest(), sha256_scope="complete" if complete else "partial",
                       elapsed_seconds=round(time.monotonic() - started, 3))
        if diagnostic is not None:
            diagnostic.clear()
            diagnostic.update(details)
        print("IDECK_GUI_FETCH_RESULT=" + json.dumps(details), flush=True)
    if failure:
        raise FetchError(details) from None
    return {k: lock["payload"][k] for k in ("size", "sha256")}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("fetch", "restore", "stage", "verify", "prepare"))
    parser.add_argument("source", type=Path)
    parser.add_argument("lock", type=Path)
    parser.add_argument("--destination", type=Path)
    parser.add_argument("--modules", type=Path)
    args = parser.parse_args()
    if args.command in ("stage", "restore") and args.destination is None:
        parser.error("--destination is required")
    if args.command == "prepare":
        if args.destination is None or args.modules is None: parser.error("--destination and --modules required")
        result = prepare(args.source, args.modules, args.destination, args.lock)
    elif args.command == "fetch":
        try: result = fetch(args.source, args.lock)
        except FetchError: raise SystemExit(1) from None
    elif args.command == "verify": result = verify(args.source, load_lock(args.lock))
    else: result = globals()[args.command](args.source, args.destination, args.lock)
    print(json.dumps(result, indent=2))
