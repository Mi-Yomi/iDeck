"""Deterministic tiny newc suffix; no downloaded binary or changed large payload."""
import argparse
import base64
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / 'guest/recovery/ideck-recovery-init'
DESKTOP = ROOT / 'guest/gui/ideck-desktop-init'
SCAN = ROOT / 'guest/recovery/fsck-clean.awk'


def desktop_runtime():
    # Retain the accepted base payload/builder byte-for-byte. The small native
    # suffix applies exactly these reviewed PID1 changes, failing on source drift.
    original = DESKTOP.read_bytes()
    changes = [(b'for name in run dev/shm dev/pts dev sys proc; do',
                b'for name in run tmp dev/shm dev/pts dev sys proc; do'),
               (b'mount -t tmpfs -o mode=0755 tmpfs /sysroot/run || fail run\n',
                b'mount -t tmpfs -o mode=0755 tmpfs /sysroot/run || fail run\n'
                b'mount -t tmpfs -o mode=1777,size=64m tmpfs /sysroot/tmp || fail tmp\n')]
    for old, new in changes:
        if original.count(old) != 1:
            raise ValueError('desktop runtime overlay no longer matches accepted PID1')
        original = original.replace(old, new)
    return original


def suffix(script):
    if not script.startswith(b'#!/bin/sh\n') or len(script) > 16384:
        raise ValueError('invalid recovery init')
    output = bytearray()
    desktop = desktop_runtime()
    if not desktop.startswith(b'#!/bin/sh\n') or len(desktop) > 16384:
        raise ValueError('invalid desktop init')
    for inode, name, mode, data in [(1, b'ideck-recovery-init', 0o100755, script),
                                  (2, b'ideck-desktop-init', 0o100755, desktop),
                                  (3, b'ideck-fsck-clean.awk', 0o100444, SCAN.read_bytes()), (0, b'TRAILER!!!', 0, b'')]:
        fields = (inode, mode, 0, 0, 1, 0, len(data), 0, 0, 0, 0, len(name)+1, 0)
        output += b'070701' + ''.join(f'{value:08x}' for value in fields).encode()
        output += name + b'\0'
        output += b'\0' * (-len(output) % 4)
        output += data
        output += b'\0' * (-len(output) % 4)
    return bytes(output)


def swift(script):
    encoded = base64.b64encode(suffix(script)).decode()
    digest = hashlib.sha256(suffix(script)).hexdigest()
    return '''// Generated by tools/recovery_guest.py; edit guest/recovery/ideck-recovery-init.
import Foundation
import CryptoKit
import Darwin

enum LinuxRecoveryGuest {
    static let sha256 = "''' + digest + '''"
    static var suffix: Data { Data(base64Encoded: "''' + encoded + '''")! }
    static func append(to original: URL, expectedSHA256: String, expectedSize: Int64, output: URL) throws {
        let fd = Darwin.open(original.path, O_RDONLY | O_NOFOLLOW | O_NONBLOCK | O_CLOEXEC)
        guard fd >= 0 else { throw LinuxDesktopDisk.Invalid.io }
        let input = FileHandle(fileDescriptor: fd, closeOnDealloc: true)
        defer { try? input.close() }
        var state = stat()
        guard fstat(fd, &state) == 0, state.st_mode & S_IFMT == S_IFREG,
              state.st_nlink == 1, state.st_size == expectedSize else { throw LinuxDesktopDisk.Invalid.metadata }
        let out = Darwin.open(output.path, O_WRONLY | O_CREAT | O_EXCL | O_NOFOLLOW | O_CLOEXEC, 0o600)
        guard out >= 0 else { throw LinuxDesktopDisk.Invalid.io }
        let destination = FileHandle(fileDescriptor: out, closeOnDealloc: true)
        defer { try? destination.close() }
        var total = 0
        var hash = SHA256()
        while let bytes = try input.read(upToCount: 1024 * 1024), !bytes.isEmpty {
            total += bytes.count
            guard total <= 32 * 1024 * 1024 else { throw LinuxDesktopDisk.Invalid.size }
            hash.update(data: bytes)
            try destination.write(contentsOf: bytes)
        }
        let digest = hash.finalize().map { String(format: "%02x", $0) }.joined()
        guard Int64(total) == expectedSize, digest == expectedSHA256 else { throw LinuxDesktopDisk.Invalid.checksum }
        // Kernel initramfs accepts concatenated compressed and raw newc archives.
        try destination.write(contentsOf: Data(repeating: 0, count: (4 - total % 4) % 4))
        try destination.write(contentsOf: suffix)
        try destination.synchronize()
    }
}
'''


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--swift', type=Path)
    p.add_argument('--base', type=Path)
    p.add_argument('--output', type=Path)
    a = p.parse_args()
    script = SCRIPT.read_bytes()
    if a.swift:
        a.swift.write_text(swift(script))
    elif a.base and a.output:
        data = a.base.read_bytes()
        a.output.write_bytes(data + b'\0' * (-len(data) % 4) + suffix(script))
    else:
        p.error('provide --swift or --base/--output')
