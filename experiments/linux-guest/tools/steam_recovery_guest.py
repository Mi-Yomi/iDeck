"""Steam12GiB journal-only derivative; accepted GUI generator stays immutable."""
import argparse
from pathlib import Path
import recovery_guest

SCRIPT = recovery_guest.SCRIPT

def steam_script():
    # Steam is journal-only: no counter mount/reconciliation or general repair.
    script = SCRIPT.read_bytes()
    old = b'[ "$(cat /sys/block/"$tools"/size)" = 2621440 ] && [ "$(cat /sys/block/"$work"/size)" = 2621440 ] || fail size'
    new = old.replace(b'"$work"/size)" = 2621440', b'"$work"/size)" = 25165824')
    if script.count(old) != 1: raise ValueError('Steam recovery source drift')
    script = script.replace(old, new)
    old = b'''for disk in "/dev/$tools" "/dev/$work"; do
    case "$(blkid "$disk")" in *'UUID="b66e1c8d-9cbf-45a7-b97b-dcc8f68efca7"'*) ;; *) fail uuid;; esac
done'''
    new = b'''case "$(blkid "/dev/$tools")" in *'UUID="b66e1c8d-9cbf-45a7-b97b-dcc8f68efca7"'*) ;; *) fail uuid;; esac
case "$(blkid "/dev/$work")" in *'UUID="c6a66b17-1b3e-4fe9-a07b-70c185fb2718"'*) ;; *) fail uuid;; esac'''
    if script.count(old) != 1: raise ValueError('Steam recovery source drift')
    script = script.replace(old, new)
    begin = script.index(b'if ! awk -f /ideck-fsck-clean.awk')
    end = script.index(b'fi\n', begin) + 3
    # The block contains no nested shell if; validate its exact ending.
    if b'IDECK_RECOVERY_SUMMARY_RECONCILED' not in script[begin:end]: raise ValueError('Steam recovery counter scope drift')
    script = script[:begin] + b'awk -f /ideck-fsck-clean.awk /run/eligibility.log 3>&- || fail manual_review\n' + script[end:]
    if script.count(b'1342177280') != 1: raise ValueError('Steam recovery image size drift')
    script = script.replace(b'1342177280', b'12884901888')
    script = script.replace(b'counter_mounted=0\n', b'').replace(b'    [ "$counter_mounted" = 0 ] || $BB umount /counter-sync || true\n', b'')
    begin = script.index(b'scope_hash() {'); end = script.index(b'image_hash() {', begin)
    script = script[:begin] + script[end:]
    begin = script.index(b'header_snapshot() {'); end = script.index(b'set_target_mode() {', begin)
    script = script[:begin] + script[end:]
    if b'/counter-sync' in script: raise ValueError('Steam recovery must not mount target')
    return script


def steam_swift():
    return recovery_guest.swift(steam_script()).replace('enum LinuxRecoveryGuest {', 'enum LinuxSteamRecoveryGuest {').replace('Generated by tools/recovery_guest.py;', 'Generated by tools/steam_recovery_guest.py;')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--swift', type=Path, required=True)
    args = parser.parse_args()
    args.swift.write_text(steam_swift())
